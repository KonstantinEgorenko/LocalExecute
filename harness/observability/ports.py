"""One-way, failure-propagating observability ports for production tracing."""
from __future__ import annotations

from typing import Any, Mapping, Protocol


class ContextBuildObserver(Protocol):
    def build_started(self, *, request: Any, budget: Mapping[str, int]) -> None: ...
    def item_considered(self, *, request: Any, item: Any | None, required: bool, selected: bool | None, omission_reason: str | None = None, artifact_ref: Any | None = None) -> None: ...
    def budget_decision(self, *, request: Any, required_items: tuple[Any, ...], optional_items: tuple[Any, ...], selected_items: tuple[Any, ...], omitted_items: tuple[Mapping[str, Any], ...], required_total: Mapping[str, int], selected_total: Mapping[str, int], overflow: Mapping[str, int], top_required_contributors: tuple[Any, ...], status: str) -> None: ...
    def build_finished(self, *, request: Any, bundle: Any, required_total: Mapping[str, int], selected_total: Mapping[str, int], omitted_items: tuple[Mapping[str, Any], ...]) -> None: ...


class ExecutionObserver(Protocol):
    def routing_started(self, *, run_id: str, todo_id: str, attempt_index: int) -> None: ...
    def routing_decision(self, *, run_id: str, todo_id: str, attempt_index: int, decision: Any) -> None: ...
    def model_call_started(self, *, run_id: str, todo_id: str, attempt_index: int, decision: Any, request: Any) -> None: ...
    def model_call_finished(self, *, run_id: str, todo_id: str, attempt_index: int, decision: Any, result: Any) -> None: ...
    def model_call_failed(self, *, run_id: str, todo_id: str, attempt_index: int, decision: Any, error: BaseException) -> None: ...
    def tool_call_started(self, *, run_id: str, todo_id: str, attempt_index: int, request: Any) -> None: ...
    def tool_call_finished(self, *, run_id: str, todo_id: str, attempt_index: int, request: Any, result: Any) -> None: ...
    def tool_call_failed(self, *, run_id: str, todo_id: str, attempt_index: int, request: Any, error: BaseException) -> None: ...
